import { readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('.', import.meta.url));
const masksDir = join(root, 'masks');
const files = await readdir(masksDir);

// Intentionally lexicographic: 1, 2, 3, 31, 32, 4, 41… rather than numeric order.
const masks = files
  .map(file => /^dv_(.+)\.png$/i.exec(file)?.[1])
  .filter(Boolean)
  .sort((a, b) => a < b ? -1 : a > b ? 1 : 0);

await writeFile(
  join(root, 'dv-manifest.js'),
  `// Generated by sync-dv-resources.mjs — do not edit manually.\nwindow.DV_MASKS = ${JSON.stringify(masks)};\n`,
  'utf8',
);

console.log(`Found ${masks.length} dv_ mask(s): ${masks.join(', ')}`);
